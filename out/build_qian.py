def make_para(level, text):
    src = TPL[level]
    new = copy.deepcopy(src)
    runs = new.findall(qn('w:r'))
    keep = runs[0]
    for r in runs[1:]:
        new.remove(r)
    for t in keep.findall(qn('w:t')):
        keep.remove(t)
    for br in keep.findall(qn('w:br')):
        keep.remove(br)
    t = keep.makeelement(qn('w:t'), {})
    t.set(qn('xml:space'), 'preserve')
    t.text = text
    keep.append(t)
    return new

